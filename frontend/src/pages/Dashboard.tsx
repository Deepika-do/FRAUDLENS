 
import React, { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import {
  BarChart, Bar, XAxis, YAxis, CartesianGrid,
  Tooltip, Legend, ResponsiveContainer
} from 'recharts';
import { FileSearch, Upload, Download } from 'lucide-react';
import { jsPDF } from 'jspdf';
import { getDashboard } from '../api';
import type { DashboardData } from '../api';
import { Spinner, EmptyState, formatDate } from '../components/ui';

const Dashboard: React.FC = () => {
  const [data, setData] = useState<DashboardData | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const navigate = useNavigate();

  useEffect(() => {
    getDashboard()
      .then(setData)
      .catch(e => setError(e?.response?.data?.detail || 'Failed to load dashboard data.'))
      .finally(() => setLoading(false));
  }, []);

  const downloadMonthlyPDF = (item: DashboardData['monthly_chart'][number]) => {
    const pdf = new jsPDF();

    const clear = Math.max(0, item.total - item.flagged);
    const percentage = item.total > 0
      ? ((item.flagged / item.total) * 100).toFixed(1)
      : '0.0';

    pdf.setFontSize(20);
    pdf.text('FraudLens - Monthly Invoice Summary', 15, 22);

    pdf.setFontSize(13);
    pdf.text(`Invoice Month: ${item.month}`, 15, 38);

    pdf.setFontSize(12);
    pdf.text('Monthly Statistics', 15, 55);

    pdf.setFontSize(11);
    pdf.text(`Total invoices scanned: ${item.total}`, 20, 68);
    pdf.text(`Invoices needing review: ${item.flagged}`, 20, 80);
    pdf.text(`Not flagged invoices: ${clear}`, 20, 92);
    pdf.text(`Percentage flagged: ${percentage}%`, 20, 104);

    pdf.setFontSize(10);
    pdf.text('Review Note:', 15, 125);
    pdf.text(
      'Invoices flagged by the system require further review.',
      15,
      134
    );
    pdf.text(
      'A flagged invoice is not confirmed fraud.',
      15,
      143
    );

    pdf.setFontSize(9);
    pdf.text('Generated by FraudLens', 15, 275);

    const safeMonth = item.month.replace(/[^a-zA-Z0-9-_]/g, '_');
    pdf.save(`FraudLens_${safeMonth}_Summary.pdf`);
  };

  if (loading) {
    return (
      <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'center', height: '100%' }}>
        <Spinner size={32} />
      </div>
    );
  }

  if (error || !data) {
    return (
      <div className="page-body">
        <div className="alert alert-error">
          {error || 'Failed to load dashboard data.'}
        </div>
      </div>
    );
  }

  const batch = data.latest_batch;
  const hasData = batch !== null && batch !== undefined;

  return (
    <>
      <div className="page-header">
        <div className="page-title">Dashboard</div>
        <div className="page-subtitle">
          {hasData
            ? `Latest batch processed ${formatDate(batch.uploaded_at)} · ${batch.total_invoices} invoice(s)`
            : 'No batches processed yet'}
        </div>
      </div>

      <div className="page-body">
        {!hasData ? (
          <div className="card">
            <EmptyState
              icon={<FileSearch size={48} />}
              title="No invoices processed yet"
              subtitle="Upload a GST invoice file to begin fraud detection analysis."
              action={
                <button
                  className="btn btn-primary"
                  onClick={() => navigate('/upload')}
                >
                  <Upload size={15} />
                  Upload Invoices
                </button>
              }
            />
          </div>
        ) : (
          <>
            <div style={{
              display: 'grid',
              gridTemplateColumns: 'repeat(auto-fit, minmax(180px, 1fr))',
              gap: 16,
              marginBottom: 24
            }}>
              <div className="metric-panel">
                <div className="metric-label">Invoices Scanned</div>
                <div className="metric-value">
                  {data.invoices_scanned.toLocaleString()}
                </div>
                <div className="metric-sub">Latest batch</div>
              </div>

              <div className="metric-panel" style={{ borderLeft: '3px solid #dc2626' }}>
                <div className="metric-label">Needs Review</div>
                <div
                  className="metric-value"
                  style={{ color: data.needs_review > 0 ? '#dc2626' : undefined }}
                >
                  {data.needs_review.toLocaleString()}
                </div>
                <div className="metric-sub">Suspicious invoices</div>
              </div>

              <div className="metric-panel">
                <div className="metric-label">Clear</div>
                <div className="metric-value" style={{ color: '#16a34a' }}>
                  {(data.invoices_scanned - data.needs_review).toLocaleString()}
                </div>
                <div className="metric-sub">Not suspicious</div>
              </div>
            </div>

            <div className="card" style={{ marginBottom: 24 }}>
              <div className="card-title">Latest Batch</div>

              <div style={{
                display: 'grid',
                gridTemplateColumns: 'repeat(auto-fit, minmax(160px, 1fr))',
                gap: 16,
                marginTop: 8
              }}>
                <div>
                  <div style={{ fontSize: 11, color: 'var(--color-text-muted)', textTransform: 'uppercase', marginBottom: 3 }}>
                    File
                  </div>
                  <div style={{ fontSize: 13, color: 'var(--color-text-primary)', fontWeight: 500 }}>
                    {batch.original_filename || '—'}
                  </div>
                </div>

                <div>
                  <div style={{ fontSize: 11, color: 'var(--color-text-muted)', textTransform: 'uppercase', marginBottom: 3 }}>
                    Uploaded
                  </div>
                  <div style={{ fontSize: 13 }}>{formatDate(batch.uploaded_at)}</div>
                </div>

                <div>
                  <div style={{ fontSize: 11, color: 'var(--color-text-muted)', textTransform: 'uppercase', marginBottom: 3 }}>
                    Invoice Period
                  </div>
                  <div style={{ fontSize: 13 }}>
                    {batch.invoice_period_start
                      ? `${batch.invoice_period_start} – ${batch.invoice_period_end || '…'}`
                      : '—'}
                  </div>
                </div>

                <div>
                  <div style={{ fontSize: 11, color: 'var(--color-text-muted)', textTransform: 'uppercase', marginBottom: 3 }}>
                    Status
                  </div>
                  <div style={{ fontSize: 13, display: 'flex', alignItems: 'center', gap: 6 }}>
                    <span
                      className={`status-dot ${
                        batch.status === 'completed' ? 'status-dot-success' :
                        batch.status === 'failed' ? 'status-dot-error' :
                        'status-dot-pending'
                      }`}
                    />
                    {batch.status.charAt(0).toUpperCase() + batch.status.slice(1)}
                  </div>
                </div>
              </div>

              <div style={{ marginTop: 16 }}>
                <button
                  className="btn btn-secondary"
                  style={{ fontSize: 12.5 }}
                  onClick={() => navigate('/results')}
                >
                  View fraud results →
                </button>
              </div>
            </div>

            {data.monthly_chart.length > 0 ? (
              <>
                <div className="card" style={{ marginBottom: 24 }}>
                  <div className="card-title">Monthly Invoice History</div>
                  <div style={{
                    fontSize: 12,
                    color: 'var(--color-text-muted)',
                    marginBottom: 16
                  }}>
                    Total invoices processed and flagged per invoice month across all batches.
                  </div>

                  <ResponsiveContainer width="100%" height={260}>
                    <BarChart
                      data={data.monthly_chart}
                      margin={{ top: 4, right: 16, left: 0, bottom: 0 }}
                    >
                      <CartesianGrid strokeDasharray="3 3" stroke="#f0f0f0" vertical={false} />
                      <XAxis
                        dataKey="month"
                        tick={{ fontSize: 11, fill: '#9ca3af' }}
                        axisLine={false}
                        tickLine={false}
                      />
                      <YAxis
                        tick={{ fontSize: 11, fill: '#9ca3af' }}
                        axisLine={false}
                        tickLine={false}
                        allowDecimals={false}
                      />
                      <Tooltip
                        contentStyle={{
                          fontSize: 12,
                          border: '1px solid #e5e7eb',
                          borderRadius: 6,
                          boxShadow: '0 2px 8px rgba(0,0,0,0.08)'
                        }}
                      />
                      <Legend
                        iconType="square"
                        iconSize={10}
                        wrapperStyle={{ fontSize: 12 }}
                      />
                      <Bar dataKey="total" fill="#93c5fd" radius={[3, 3, 0, 0]} name="Total Invoices" />
                      <Bar dataKey="flagged" fill="#fca5a5" radius={[3, 3, 0, 0]} name="Needs Review" />
                    </BarChart>
                  </ResponsiveContainer>
                </div>

                <div className="card">
                  <div className="card-title">Download Monthly Reports</div>
                  <p style={{
                    fontSize: 12,
                    color: 'var(--color-text-muted)',
                    marginBottom: 16
                  }}>
                    Download a PDF report for each month.
                  </p>

                  {data.monthly_chart.map((item, index) => (
                    <div
                      key={`${item.month}-${index}`}
                      style={{
                        display: 'flex',
                        justifyContent: 'space-between',
                        alignItems: 'center',
                        gap: 12,
                        padding: '12px 0',
                        borderBottom: index === data.monthly_chart.length - 1
                          ? 'none'
                          : '1px solid var(--color-border, #e5e7eb)'
                      }}
                    >
                      <div>
                        <div style={{ fontSize: 13, fontWeight: 600 }}>
                          {item.month}
                        </div>
                        <div style={{
                          fontSize: 12,
                          color: 'var(--color-text-muted)',
                          marginTop: 3
                        }}>
                          {item.total} total · {item.flagged} needing review
                        </div>
                      </div>

                      <button
                        className="btn btn-secondary"
                        style={{ fontSize: 12.5, whiteSpace: 'nowrap' }}
                        onClick={() => downloadMonthlyPDF(item)}
                      >
                        <Download size={14} />
                        Download PDF
                      </button>
                    </div>
                  ))}
                </div>
              </>
            ) : (
              <div className="card">
                <div className="card-title">Monthly Invoice History</div>
                <div className="empty-state" style={{ padding: '32px 24px' }}>
                  <div className="empty-state-sub">
                    Monthly chart data will appear here after invoices with valid dates are processed.
                  </div>
                </div>
              </div>
            )}
          </>
        )}
      </div>
    </>
  );
};

export default Dashboard;
